//! Explicit, current-user systemd setup. Ordinary connections never install or upgrade it.
use super::*;
use eon_workspace_protocol::v13::{
    HEADER_BYTES, Request, declared_message_len, decode_request, encode_response,
};

pub(crate) fn command(inputs: &Inputs, arguments: &[OsString]) -> Result<i32, String> {
    let values = arguments
        .iter()
        .map(|value| {
            value
                .to_str()
                .ok_or("server commands require UTF-8 arguments")
        })
        .collect::<Result<Vec<_>, _>>()?;
    match values.as_slice() {
        ["service", "install"] => install(),
        ["doctor", "--json"] => {
            let (manager, linger) = readiness();
            crate::control::write_stdout(format!(
                "{}\n",
                serde_json::json!({"user_manager": manager, "linger": linger, "ready": manager && linger, "uid": effective_uid()})
            ))?;
            Ok(i32::from(!manager || !linger))
        }
        ["serve", "--workspace", id] => {
            require_ready()?;
            serve(inputs, id, true, false)
        }
        ["bootstrap"] => bootstrap(inputs),
        ["--help"] | ["-h"] => {
            crate::control::write_stdout(
                "eon-server service install\neon-server doctor --json\neon-server serve --workspace ID\n",
            )?;
            Ok(0)
        }
        _ => Err("usage: eon-server service install | doctor --json | serve --workspace ID".into()),
    }
}

fn readiness() -> (bool, bool) {
    let manager = Command::new("systemctl")
        .args(["--user", "show-environment"])
        .output()
        .is_ok_and(|output| output.status.success());
    let linger = Command::new("loginctl")
        .args([
            "show-user",
            &effective_uid().to_string(),
            "--property=Linger",
            "--value",
        ])
        .output()
        .is_ok_and(|output| output.status.success() && output.stdout == b"yes\n");
    (manager, linger)
}
fn require_ready() -> Result<(), String> {
    if effective_uid() == 0 {
        return Err("remote workspaces require an ordinary user account".into());
    }
    let (manager, linger) = readiness();
    if !manager || !linger {
        return Err(format!(
            "remote workspace hosting is not ready (user manager: {manager}, linger: {linger}); enable linger for this account with loginctl enable-linger and start its systemd user manager, then run eon-server service install"
        ));
    }
    Ok(())
}
fn unit_word(value: &std::ffi::OsStr) -> Result<String, String> {
    let value = value.to_str().ok_or("systemd unit paths must be UTF-8")?;
    if value.chars().any(char::is_control) {
        return Err("systemd unit paths cannot contain control characters".into());
    }
    Ok(format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('%', "%%")
    ))
}
fn install() -> Result<i32, String> {
    require_ready()?;
    let program = nonempty_environment_path("EON_SERVER_PROGRAM")
        .ok_or("service installation requires the packaged eon-server launch program")?;
    if !program.is_absolute() || !program.is_file() {
        return Err("the server launch program must be an existing absolute path".into());
    }
    let config_root = nonempty_environment_path("XDG_CONFIG_HOME")
        .filter(|path| path.is_absolute())
        .or_else(|| env::home_dir().map(|home| home.join(".config")))
        .ok_or("cannot resolve systemd user unit directory")?;
    let directory = config_root.join("systemd/user");
    fs::create_dir_all(&directory).map_err(|error| error.to_string())?;
    let path = directory.join("eon-workspace@.service");
    let marker = "# Generated by Eon: current-user named workspaces\n";
    if path.exists() {
        let metadata = fs::symlink_metadata(&path).map_err(|error| error.to_string())?;
        if !metadata.file_type().is_file()
            || metadata.uid() != effective_uid()
            || !fs::read_to_string(&path)
                .map_err(|error| error.to_string())?
                .starts_with(marker)
        {
            return Err("refusing to replace an unowned Eon service unit".into());
        }
    }
    let mut environment = String::new();
    for key in [
        "EON_CONFIG_HOME",
        "XDG_CONFIG_HOME",
        "XDG_STATE_HOME",
        "EON_RUNTIME_DIR",
        "PATH",
    ] {
        if let Some(value) = env::var_os(key).filter(|value| !value.is_empty()) {
            let mut assignment = OsString::from(format!("{key}="));
            assignment.push(value);
            environment.push_str(&format!("Environment={}\n", unit_word(&assignment)?));
        }
    }
    // ExecStart expands dollars; Environment only expands percent specifiers.
    let program_word = unit_word(program.as_os_str())?.replace('$', "$$");
    let unit = format!(
        "{marker}[Unit]\nDescription=Eon workspace %i\n\n[Service]\nType=simple\n{environment}ExecStart={program_word} serve --workspace %i\nRestart=no\n"
    );
    let temporary = directory.join(format!(".eon-workspace-{}", request_id()));
    let mut file = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(&temporary)
        .map_err(|error| error.to_string())?;
    file.write_all(unit.as_bytes())
        .and_then(|()| file.sync_all())
        .map_err(|error| error.to_string())?;
    fs::rename(&temporary, &path).map_err(|error| error.to_string())?;
    let status = Command::new("systemctl")
        .args(["--user", "daemon-reload"])
        .status()
        .map_err(|error| error.to_string())?;
    if !status.success() {
        return Err("systemd user daemon-reload failed".into());
    }
    crate::control::write_stdout(format!(
        "Installed {}\nLaunch program: {}\nKeep this build in an explicit Nix profile or GC root while its workspaces run. Existing supervisors were left running.\n",
        path.display(),
        program.display()
    ))?;
    Ok(0)
}

/// A fixed SSH entry point; user values travel only in the bounded stdin frame.
fn bootstrap(inputs: &Inputs) -> Result<i32, String> {
    let mut stdin = std::io::stdin().lock();
    let mut bytes = vec![0; HEADER_BYTES];
    stdin
        .read_exact(&mut bytes)
        .map_err(|error| format!("cannot read bootstrap request: {error}"))?;
    let length = declared_message_len(&bytes).map_err(|error| error.to_string())?;
    if length > 8192 {
        return Err("bootstrap request exceeds its size limit".into());
    }
    bytes.resize(length, 0);
    stdin
        .read_exact(&mut bytes[HEADER_BYTES..])
        .map_err(|error| error.to_string())?;
    let Request { action, .. } = decode_request(&bytes).map_err(|error| error.to_string())?;
    let result = match action {
        Action::Registry(RegistryAction::List) => list(inputs).map(Response::Registry),
        Action::Registry(RegistryAction::Create { name }) => require_ready()
            .and_then(|()| create(inputs, &name))
            .and_then(|value| ensure(inputs, &value.id, true))
            .map(Response::Hello),
        Action::Registry(RegistryAction::Ensure { workspace }) => require_ready()
            .and_then(|()| ensure(inputs, &workspace, true))
            .map(Response::Hello),
        Action::Registry(RegistryAction::Stop { workspace }) => {
            stop_named(inputs, &workspace, true)
                .and_then(|()| list(inputs))
                .map(Response::Registry)
        }
        Action::Registry(RegistryAction::Forget { workspace }) => forget(inputs, &workspace)
            .and_then(|()| list(inputs))
            .map(Response::Registry),
        _ => Err("bootstrap accepts only registry operations".into()),
    };
    let response =
        result.unwrap_or_else(|detail| Response::Failure(failure("remote-workspace", detail)));
    std::io::stdout()
        .lock()
        .write_all(&encode_response(&response).map_err(|error| error.to_string())?)
        .map_err(|error| error.to_string())?;
    Ok(0)
}
